"""The stylesheet is GENERATED from the tokens, so a colour outside the palette cannot reach it."""
from __future__ import annotations

import colorsys
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "src"))

from cdfc.surface import design  # noqa: E402
from cdfc.surface.stylesheet import stylesheet  # noqa: E402

HEX = re.compile(r"#([0-9a-fA-F]{6})\b")


def test_style__no_literal_colour_outside_the_palette() -> None:
    """The fastest way to reintroduce an affirmative green is to type one."""
    palette = {v.lstrip("#").lower() for v in design.COLOR.values() if v.startswith("#")}
    found = {h.lower() for h in HEX.findall(stylesheet())}
    assert found <= palette, f"colours not in COLOR reached the stylesheet: {sorted(found - palette)}"


def test_style__no_colour_falls_in_the_green_hue_band() -> None:
    """SG4's rule, asserted over the generated bytes: hue 80-160 with real saturation reads as a
    success colour whatever it is named."""
    for h in HEX.findall(stylesheet()):
        r, g, b = (int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))
        hue, light, sat = colorsys.rgb_to_hls(r, g, b)
        assert not (80.0 <= hue * 360 <= 160.0 and sat > 0.15 and 0.20 <= light <= 0.80), \
            f"#{h} is a green"


def test_style__the_two_hero_lines_take_exactly_one_rule() -> None:
    """One selector means no stylesheet can give one of them the accent — and the line that would
    lose is the count of fields nobody checked."""
    css = stylesheet()
    assert len(re.findall(r"^\.hero \{", css, re.M)) == 1
    assert not re.search(r"\.hero:(first|last|nth)", css)


def test_style__the_hatch_is_a_pattern_and_not_a_muted_fill() -> None:
    """A muted segment reads as *less important*; a hatched one reads as *a different kind of
    thing*, which is what it is."""
    css = stylesheet()
    assert "repeating-linear-gradient" in css
    assert not re.search(r"\.seg-hatch\s*\{[^}]*opacity", css)


def test_style__reduced_motion_removes_every_animation() -> None:
    """With rule one in force the reduced rendering carries identical content, which is what makes
    it the proof that no content is gated on an animation."""
    css = stylesheet()
    assert "prefers-reduced-motion" in css
    block = css.split("prefers-reduced-motion")[1]
    assert "animation: none" in block and "opacity: 1" in block


def test_style__the_effect_layer_is_behind_the_content() -> None:
    css = stylesheet()
    assert ".wash" in css and "z-index: 0" in css
    assert "z-index: 1" in css
