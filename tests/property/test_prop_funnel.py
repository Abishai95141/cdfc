"""P12-B4 — the funnel is monotone, and the hand-off between stages is an EQUALITY.

`survived ≤ entered` is the obvious half. The half that matters is `stages[i].survived ==
stages[i+1].entered`: a *gap* between two stages is a population that left the measurement without
being counted anywhere, and it renders as a slightly steeper bar chart rather than as an error. That
is the one defect in this module that a reader of `funnel.json` could not detect, which is why it is
asserted over arbitrary tallies rather than over the two shapes a hand-written example would use.

The two shapes a hand-written example *would* use are pinned as `@example`s anyway, because they are
the ends of the range and both are real outcomes of this experiment: 600:0, where every candidate
dies and the funnel is at its most informative, and 600:600, where no gate fires at all — which
would mean the gates are not gating, and must still build a legal funnel so that it can be read.
"""

from __future__ import annotations

import sys
from pathlib import Path

import pytest
from hypothesis import HealthCheck, example, given, settings
from hypothesis import strategies as st

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "src"))

from cdfc.experiment.funnel import (  # noqa: E402
    STAGE_ORDER,
    FunnelInvariantViolated,
    RejectionRow,
    funnel,
)

PROFILE = settings(
    max_examples=300, deadline=None, derandomize=True,
    suppress_health_check=[HealthCheck.too_slow],
)

TALLIES = st.lists(st.integers(min_value=0, max_value=8),
                   min_size=len(STAGE_ORDER), max_size=len(STAGE_ORDER))
SURVIVORS = st.integers(min_value=0, max_value=8)


def _rows(deaths: list[int]) -> list[RejectionRow]:
    out: list[RejectionRow] = []
    for gate, n in zip(STAGE_ORDER, deaths, strict=True):
        for _ in range(n):
            out.append(RejectionRow(
                candidate_sha256=f"{len(out):064x}", gate=gate,
                reason=f"rejected at {gate}", measured="K/O = 0.00 against a bar of > 0",
                cells_it_would_have_covered=1,
            ))
    return out


@PROFILE
@given(TALLIES, SURVIVORS)
@example([0] * len(STAGE_ORDER), 0)          # nothing generated at all
@example([0] * len(STAGE_ORDER), 8)          # every candidate survives every gate
@example([8, 0, 0, 0, 0, 0, 0, 0], 0)        # 600:0 — the funnel at its most informative
@example([0, 0, 0, 0, 0, 0, 0, 8], 0)        # everything dies at the last gate
@example([1, 1, 1, 1, 1, 1, 1, 1], 1)        # one death at every gate
def test_prop__the_funnel_is_monotone_and_hands_off_exactly(deaths: list[int],
                                                            survivors: int) -> None:
    """`survived ≤ entered` everywhere, and `stages[i].survived == stages[i+1].entered` exactly.

    A gap in the hand-off is a population that left the funnel uncounted — invisible in the
    rendered chart, and the one way this artefact could overstate attrition without any single
    stage being wrong. The total is checked from both ends too: stage 0 is the planned count, and
    the last stage's survivors are the planned count minus every rejection row, so a rejection that
    was filed but never subtracted (or subtracted twice) fails here.
    """
    planned = sum(deaths) + survivors
    out = funnel(
        [f"cand-{i}" for i in range(planned)], _rows(deaths),
        obligations=planned, regimes=1, k=1,
    )

    assert tuple(s.name for s in out.stages) == STAGE_ORDER
    assert out.planned == planned
    assert out.stages[0].entered == planned, "stage 0 is the planned count, discards included"

    for stage in out.stages:
        assert 0 <= stage.survived <= stage.entered
        assert stage.entered - stage.survived == len(stage.rejections)

    for a, b in zip(out.stages, out.stages[1:], strict=False):
        assert a.survived == b.entered, (
            f"{a.name} passed {a.survived} to {b.name}, which received {b.entered}"
        )

    assert out.survived == survivors == planned - sum(deaths)
    assert sum(len(s.rejections) for s in out.stages) == sum(deaths)
    assert len(out.as_obj()["stages"]) == len(STAGE_ORDER)


@PROFILE
@given(TALLIES, SURVIVORS, st.integers(min_value=1, max_value=5))
def test_prop__a_rejection_the_records_cannot_account_for_is_refused(
    deaths: list[int], survivors: int, extra: int,
) -> None:
    """More deaths than candidates is not a small inconsistency; it is a different denominator.

    Generated by adding rejection rows the record set never contained — the shape a merge of two
    runs, or a re-run appended to an old rejection log, would take. It must fail loudly: a funnel
    that absorbed the surplus by clamping at zero would publish an attrition that no set of
    candidates produced.
    """
    planned = sum(deaths) + survivors
    surplus = list(deaths)
    surplus[0] += survivors + extra
    with pytest.raises(FunnelInvariantViolated):
        funnel(
            [f"cand-{i}" for i in range(planned)], _rows(surplus),
            obligations=planned, regimes=1, k=1,
        )
