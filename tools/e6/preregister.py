# The date this criterion was committed. A PARAMETER, never a clock read: nothing under `src/` or
# `tools/measure/` reads the wall clock, and a lock whose timestamp came from the machine that
# wrote it can be re-written on a machine whose clock was set differently.
COMMITTED_AT = "2026-08-15"

# The chapters that would be sampled. They are named here rather than in code because the chapter
# set is part of the pool's construction and therefore part of what is hashed. **On today's tree
# no statutory instrument is pinned, so this list has nothing to match against** — and
# `enumerate_shall` raises rather than matching loosely, which is why the pool is absent rather
# than small. See docs/decisions/D-P7-01-no-statutory-instrument.md.
