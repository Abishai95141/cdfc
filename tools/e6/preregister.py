"""P12-B1 — generate `experiments/E6/PREREGISTRATION.md` and lock it.

**The document is GENERATED, and that is the repair for F30's shape.** A hand-authored
pre-registration carrying a hand-typed power table is two artifacts that agree until somebody
edits one; here the tables come from `cdfc.experiment.power.power_table()` and the thresholds come
from the module constants, so `test_e6__power_table_matches_preregistration` and
`test_contract__preregistration_criterion_is_machine_evaluable` are checking a **round trip**
rather than a transcription.

    make preregister      # writes the document, then locks it

`lock()` refuses to write a lock for a criterion `decide()` cannot consume, so a prose threshold
does not reach the file and the experiment therefore does not run.
"""

from __future__ import annotations

import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
