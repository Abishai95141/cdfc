#!/usr/bin/env python
"""Generate `docs/PROVISO-MARKERS-v1.md` from `qualify/provisos.py`. Never hand-edited."""

from __future__ import annotations

import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))

from cdfc.qualify.provisos import MARKERS, MARKERS_VERSION, recall  # noqa: E402

OUT = REPO / "docs" / f"PROVISO-MARKERS-{MARKERS_VERSION}.md"


def render() -> str:
    r = recall(REPO / "fixtures/predicates/proviso-labels.json")
    L = [
        f"# docs/PROVISO-MARKERS-{MARKERS_VERSION}.md — the proviso marker list",
        "",
        "GENERATED by `tools/gen_proviso_markers_doc.py` from `src/cdfc/qualify/provisos.py`.",
        "Do not hand-edit: a marker list a document and the code disagree about is a list nobody",
        "is applying.",
        "",
        f"**Version `{MARKERS_VERSION}`.** The version enters `qualification.g0`, so a predicate",
        "qualified under one list is not silently re-qualified when the list grows.",
        "",
        "## The normalisation this list assumes",
        "",
        "| property | value | why |",
        "|---|---|---|",
        "| case | **insensitive** | statutory prose capitalises at a sentence start; `Provided` and `provided` are one marker |",
        "| word boundary | **required** (`\\b`) | without it `except` matches inside `exception` and the count inflates |",
        "| whitespace | `\\s+` between words | the instrument text is already whitespace-collapsed (`textsource.normalise`), and the pattern does not depend on that having happened |",
        "| overlaps | **kept** | `Provided further that` is a different fact from `Provided that`; collapsing them under-counts a clause carrying several |",
        "",
        "**What it deliberately does not do.** It does not stem, lemmatise, or fold dashes and",
        "quotes — `textsource.REFUSED_TRANSFORMATIONS` records why for the text, and the same",
        "reasoning holds here: a folded homoglyph is a homoglyph nothing can catch.",
        "",
        f"## The {len(MARKERS)} markers",
        "",
        "| # | kind | pattern | exemplar |",
        "|---:|---|---|---|",
    ]
    for i, m in enumerate(MARKERS, start=1):
        L.append(f"| {i} | `{m.kind}` | `{m.pattern}` | {m.exemplar} |")
        if m.note:
            L.append(f"| | | | *{m.note}* |")
    L += [
        "",
        "## Recall",
        "",
        f"    {r.render()}",
        "",
        "**The number is the deliverable, not a threshold.** A detector whose recall is unmeasured",
        "is exactly the instrument this project refuses to ship, so while the labelled set is empty",
        "`provisos.assert_measured_for_statute` REFUSES every `source == STATUTE` candidate at G0",
        "rather than passing it on an unmeasured detector. There are no such candidates today",
        "(D-P7-01), so nothing is blocked — and the moment one exists, it is blocked until somebody",
        "labels.",
        "",
        "`fixtures/predicates/proviso-labels.json` carries the procedure for filling it.",
        "",
    ]
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    OUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)}")
