#!/usr/bin/env python
"""P7-B0 — build `corpus/instruments/` from the pinned blanks, and publish the agreement.

    make instruments

Writes one `<instrument_id>.text.json` per prescribed workbook, a `MANIFEST.json` census, and
`docs/measurements/P7-textsource.md`. Everything here is a pure function of the nine files'
bytes: run it twice and the tree is byte-identical.
"""

from __future__ import annotations

import hashlib
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))

from cdfc.qualify.instruments import (  # noqa: E402
    STATUTE_ABSENT_REASON,
    InstrumentRow,
    manifest_bytes,
    row_of,
    serialise,
)
from cdfc.qualify.template_instrument import emit  # noqa: E402
from cdfc.qualify.textsource import REFUSED_TRANSFORMATIONS, TRANSFORMATIONS  # noqa: E402

PRESCRIBED = REPO / "fixtures/prescribed"
OUT = REPO / "corpus/instruments"
DOC = REPO / "docs/measurements/P7-textsource.md"


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    for stale in sorted(OUT.glob("*.text.json")):
        stale.unlink()

    rows: list[InstrumentRow] = []
    instruments = []
    for blob in sorted(PRESCRIBED.glob("*.xlsx")):
        it = emit(blob)
        sha = hashlib.sha256(blob.read_bytes()).hexdigest()
        (OUT / f"{it.instrument_id}.text.json").write_bytes(
            serialise(it, kind="TEMPLATE", source_name=blob.name, source_sha256=sha)
        )
        rows.append(row_of(it, kind="TEMPLATE", source_name=blob.name, source_sha256=sha))
        instruments.append(it)
        print(f"  {it.instrument_id}  {rows[-1].units_total:5d} units  {blob.name[:44]}")

    (OUT / "MANIFEST.json").write_bytes(manifest_bytes(rows))
    DOC.write_text(_render(rows, instruments), encoding="utf-8")
    print(f"\nwrote {len(rows)} instrument(s), MANIFEST.json and {DOC.relative_to(REPO)}")
    return 0


def _render(rows: list[InstrumentRow], instruments: list) -> str:
    tot_units = sum(r.units_total for r in rows)
    tot_agreed = sum(r.agreed for r in rows)
    tot_single = sum(r.single_party for r in rows)
    tot_disp = sum(r.disputed for r in rows)
    ext_n = sum(r.external[0] for r in rows)
    ext_d = sum(r.external[1] for r in rows)
    same_n = sum(r.same_author[0] for r in rows)
    same_d = sum(r.same_author[1] for r in rows)

    L = [
        "# docs/measurements/P7-textsource.md — the instrument text source (P7-B0)",
        "",
        "GENERATED by `tools/build_instruments.py`. Do not hand-edit.",
        "",
        "**What this measures.** Every span a gate resolves points into a text produced here. The",
        "text is built from two INDEPENDENT extractions of one artifact, compared unit-wise; a unit",
        "the parties disagree on is EXCLUDED from the addressable text and listed below with its",
        "sheet ordinal. A span into an excluded unit raises rather than returning characters, and",
        "G0 turns that into `g0.quote_in_disputed_region`.",
        "",
        "## The two vectors, and why there are two",
        "",
        "A single agreement figure would average a check against a library nobody here wrote with a",
        "check of two implementations by one author. `ingest/agreement.py` bans that on every",
        "surface and the same rule holds here.",
        "",
        f"* **EXTERNAL — `{ext_n} / {ext_d}`** units where a party written outside this repository",
        "  was competent and agreed. The external party is `openpyxl`.",
        f"* **SAME-AUTHOR — `{same_n} / {same_d}`** units checked only by two implementations from",
        "  this repository. There is no such unit in this corpus: the second party on every",
        "  comparable unit is the external one.",
        "",
        "**What the external check is actually worth here, stated plainly because it is the reason",
        "this build is not ceremonial.** `211 of FME's 505 formula cells are shared dependents`,",
        "and a shared dependent's expression **exists nowhere in the file** — `<f t=\"shared\"",
        "si=\"0\"/>` carries no text. Their text is COMPUTED by `calc/shift.materialise`. Until this",
        "build, nothing checked that computation against a second implementation. It is now checked",
        "against `openpyxl`'s independent translator on every such cell in the corpus.",
        "",
        "## Corroboration — all four integers",
        "",
        "| instrument | source | units | AGREED | SINGLE_PARTY | DISPUTED | EXTERNAL |",
        "|---|---|---:|---:|---:|---:|---|",
    ]
    for r in rows:
        L.append(
            f"| `{r.instrument_id}` | {r.source_name[:38]} | {r.units_total} | {r.agreed} | "
            f"{r.single_party} | {r.disputed} | {r.external[0]}/{r.external[1]} |"
        )
    L += [
        f"| **total** | 9 pinned blanks | **{tot_units}** | **{tot_agreed}** | **{tot_single}** | "
        f"**{tot_disp}** | **{ext_n}/{ext_d}** |",
        "",
        "`SINGLE_PARTY` is neither agreement nor disagreement: exactly one party was competent, so",
        "the reading is uncorroborated. It stays addressable and it is counted separately, and a G0",
        "outcome records the corroboration of the unit it located in. Collapsing it into `AGREED`",
        "would make an unchecked reading look checked; collapsing it into `DISPUTED` would remove",
        f"{tot_single} constructs from the addressable text for a disagreement nobody observed.",
        "",
        "## The declared blindnesses, and the evidence for each",
        "",
        "| party | instrument | blind units | mechanism |",
        "|---|---|---:|---|",
    ]
    for it in instruments:
        for m in it.manifests:
            if m.n_blind:
                for mech in m.exclusion_mechanisms:
                    L.append(f"| `{m.extractor}` | `{it.instrument_id}` | {m.n_blind} | {mech} |")
    L += [
        "",
        "**An absence is not an exclusion unless a mechanism says so.** `textsource.build()` refuses",
        "an extraction that produced nothing at a key another party read and declared no mechanism",
        "for it, and `template_instrument.emit()` checks each declared blindness against evidence on",
        "the artifact — an `x14` namespace on this repository's record, or an `ArrayFormula` object",
        "`openpyxl` itself returned. Without that rule a reader that silently dropped a construct",
        "would be labelled merely uncorroborated.",
        "",
        "## Disputed regions",
        "",
    ]
    disputes = [(it.instrument_id, d) for it in instruments for d in it.disputed]
    if disputes:
        L += ["| instrument | unit | sheet ordinal | readings |", "|---|---|---:|---|"]
        for iid, d in disputes:
            readings = " · ".join(f"`{p}`: `{t[:60]}`" for p, t in sorted(d.readings.items()))
            L.append(f"| `{iid}` | `{d.key}` | {d.page} | {readings} |")
    else:
        L += [
            f"**None — `{tot_disp}` of `{tot_units}` units.** The addressable text is the whole",
            "instrument on all nine artifacts, so the risk this build was scheduled against — *the",
            "extractions disagree on more than one unit in twenty, and G0's addressable text ships",
            f"as a fraction of the instrument* — did not materialise. That threshold is `{tot_units // 20}`",
            f"of `{tot_units}` units on this corpus.",
            "",
            "**A zero is only evidence if the instrument that produced it can produce a non-zero.**",
            "`tests/differential/test_diff__two_extractions_agree.py` perturbs the shared-formula",
            "shift by one row and asserts the harness reports the dispute, and NC-Q47 asserts that",
            "dropping the second party makes a disputed span addressable again. The zero above is a",
            "measurement, not an absence of measuring.",
        ]
    L += [
        "",
        "## The normalisation, and what it deliberately does not do",
        "",
        "The list is ordered, named, and inside each instrument's digest: changing how text is",
        "normalised changes the instrument's identity, so a span cannot silently re-point.",
        "",
        "| # | transformation | why |",
        "|---:|---|---|",
    ]
    for i, (name, why) in enumerate(TRANSFORMATIONS, start=1):
        L.append(f"| {i} | `{name}` | {why} |")
    L += ["", "| refused | why |", "|---|---|"]
    for name, why in REFUSED_TRANSFORMATIONS:
        L.append(f"| `{name}` | {why} |")
    L += [
        "",
        "## The statutory corpus",
        "",
        "**`statute_instruments: []` — there is no pinned statute in this repository.**",
        "",
        STATUTE_ABSENT_REASON,
        "",
        "So P7's obligation-coverage pair reads `predicates_with_a_STATUTE_obligation = 0 / N` for a",
        "harder reason than the plan anticipated, and `docs/measurements/P7-attrition.md` carries",
        "both numbers of that pair on the same line or neither.",
        "",
    ]
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    raise SystemExit(main())
