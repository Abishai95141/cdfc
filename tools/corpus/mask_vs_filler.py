#!/usr/bin/env python
"""F36 — the only external instrument that can falsify the 3,747-cell denominator.

    make mask-check

From `corpus/MANIFEST.json`'s per-workbook `cells_written[]`, publish **two integers**:

* cells a competent filler wrote that lie **OUTSIDE** the mask — *the mask is too small, and every
  settled fraction computed against it OVERSTATES coverage. This is the dangerous direction.*
* cells inside the mask that **no filler ever wrote** — the mask is too large, and the settled
  fraction understates.

**The test asserts the two integers are computed and published, not that they are zero.** A
non-zero first integer is a finding against P2's denominator and is escalated there, not absorbed
here.
"""

from __future__ import annotations

import json
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "src"))

MANIFEST = REPO / "corpus" / "MANIFEST.json"
OUT = REPO / "docs" / "measurements" / "P8-mask-external-check.md"

ABSENT_REASON = (
    "No blind-fill corpus exists (D-P8-01), so no `cells_written[]` set exists to compare the mask "
    "against. **The two integers are NOT MEASURED**, and that is published as their value rather "
    "than as an empty section: the 3,747-cell denominator has never been checked by an instrument "
    "outside this repository, and it is the number every settled fraction is computed against."
)


def mask() -> frozenset[str]:
    """The 3,747-cell field surface, from `styles.xml`'s unlocked mask (P2)."""
    from cdfc.measure.p5_run import fme_surface

    _n, cells, _state = fme_surface()
    return frozenset(cells)


def compare(written: frozenset[str], surface: frozenset[str]) -> tuple[int, int]:
    """`(outside_the_mask, inside_but_never_written)`. TWO integers, always both."""
    return len(written - surface), len(surface - written)


def main() -> int:
    surface = mask()
    if not MANIFEST.is_file():
        OUT.write_text(_render(len(surface), None, None), encoding="utf-8")
        print(f"wrote {OUT.relative_to(REPO)} — NOT MEASURED ({MANIFEST.relative_to(REPO)} absent)")
        return 0
    doc = json.loads(MANIFEST.read_text(encoding="utf-8"))
    written: set[str] = set()
    for wb in doc.get("workbooks", ()):
        written |= set(wb.get("cells_written") or ())
    outside, unwritten = compare(frozenset(written), surface)
    OUT.write_text(_render(len(surface), outside, unwritten), encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)} — outside {outside}, never-written {unwritten}")
    return 0


def _render(n_surface: int, outside: int | None, unwritten: int | None) -> str:
    L = [
        "# docs/measurements/P8-mask-external-check.md — F36",
        "",
        "GENERATED by `tools/corpus/mask_vs_filler.py`. Do not hand-edit.",
        "",
        f"**Denominator: the {n_surface}-cell field surface** (`styles.xml` unlocked mask, rule v3,",
        "computed twice and agreed at P2).",
        "",
        "| direction | integer | what a non-zero means |",
        "|---|---:|---|",
    ]
    if outside is None:
        L += [
            "| cells a filler wrote OUTSIDE the mask | **NOT MEASURED** | the mask is too small "
            "and every settled fraction OVERSTATES coverage — **the dangerous direction** |",
            "| cells inside the mask no filler wrote | **NOT MEASURED** | the mask is too large "
            "and the settled fraction understates |",
            "",
            ABSENT_REASON,
            "",
            "**This is the only external check on the denominator in the whole plan**, and it costs "
            "one script over data the corpus lane already produces. It is unrunnable for exactly as "
            "long as the corpus lane is unstaffed.",
        ]
    else:
        L += [
            f"| cells a filler wrote OUTSIDE the mask | **{outside}** | the mask is too small and "
            "every settled fraction OVERSTATES coverage — **the dangerous direction** |",
            f"| cells inside the mask no filler wrote | **{unwritten}** | the mask is too large and "
            "the settled fraction understates |",
            "",
            "**A non-zero first integer is a finding against P2's denominator and is escalated "
            "there, not absorbed here.**",
        ]
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    raise SystemExit(main())
