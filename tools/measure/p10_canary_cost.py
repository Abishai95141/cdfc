#!/usr/bin/env python
"""P10-B1 — the measured canary cost and the `MAX_WITNESSES ∈ {1,3,5}` calibration curve.

Two things this file produces, and the second is the one `plan/05` §5.1 bought an extra half-day
for:

1. **`PERF-CANARY2` MEASURED**, replacing the ≈70 ms figure that was DERIVED from the campaign's
   throughput. The measurement goes to `reports/perf/<run_id>.jsonl` — outside `run.jsonl`, outside
   the attestation, outside everything `verify` compares (adversary F23) — and the document below
   quotes it from there.

2. **The calibration curve.** `MAX_WITNESSES = 3` ships `PROVISIONAL` because *nothing in the
   corpus argues for 3*. The curve is inapplicability at `{1, 3, 5}`, and it either closes the
   constant or leaves it rendering `PROVISIONAL` (§5.1, adversary F44).

**The surface it measures is a calibration surface, not an FFR corpus** (§0.3, F2/F44), and the
document says so on its own face. An inapplicability rate measured on filings this project
generated says what OUR filings can demonstrate; it does not say what a filer's return would.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "src"))

from cdfc.evaluate.liveness import run as run_liveness  # noqa: E402
from cdfc.measure.p10_run import (  # noqa: E402
    all_predicates,
    liveness_for,
    population,
    run_filing,
)
from cdfc.measure.p5_run import INDEPENDENT, SEEDED, TEMPLATE_COMPUTED  # noqa: E402
from cdfc.measure.perf import canary_timings as T  # noqa: E402
from cdfc.selfcheck.thresholds import (  # noqa: E402
    CALIBRATION_SETTINGS,
    CANARY_INAPPLICABLE_CEILING,
    MAX_WITNESSES,
    MAX_WITNESSES_STATUS,
)

DOC = REPO / "docs" / "measurements" / "P10-canary-cost.md"
SPARSE = REPO / "fixtures" / "synthetic" / "formula-overwritten__portfolio-O7.xlsx"

FILINGS = [
    ("clean, template-computed", TEMPLATE_COMPUTED),
    ("clean, independently computed (LibreOffice)", INDEPENDENT),
    ("one seeded fault", SEEDED),
    ("sparsely filled", SPARSE),
]

CALIBRATION_LABEL = (
    "CALIBRATION SURFACE, NOT AN FFR CORPUS. These filings were generated by this project. The "
    "curve says what OUR filings can demonstrate about the instrument; it says nothing about what "
    "a filer's return would demonstrate, and it may not be cited as a false-failure rate."
)


def main() -> int:
    # --- the measured cost ------------------------------------------------------------------
    ins = liveness_for(TEMPLATE_COMPUTED)
    (report, disp), elapsed = T.timed(lambda: run_liveness(ins))
    proof = report.as_liveness_proof()
    run_id = ins.image.filing_sha256[:16]
    timing = T.Timing(
        run_id=run_id, budget_id=T.BUDGET_ID, stage="canary+anti",
        elapsed_ms=elapsed, n=proof["canariesRun"] + proof["antiCanariesRun"],
    )
    perf_path = T.write([timing])

    # --- the calibration curve --------------------------------------------------------------
    curve = []
    for k in CALIBRATION_SETTINGS:
        rep, dsp = run_liveness(liveness_for(TEMPLATE_COMPUTED, max_witnesses=k))
        p = rep.as_liveness_proof()
        curve.append(
            {
                "max_witnesses": k,
                "canariesRun": p["canariesRun"],
                "canariesPassed": p["canariesPassed"],
                "inapplicable": p["canariesInapplicable"],
                "indeterminate": p["canariesIndeterminate"],
                "valid": dsp.valid,
            }
        )

    # --- the four filings -------------------------------------------------------------------
    runs = []
    for label, path in FILINGS:
        res = run_filing(path)
        p = res.liveness.as_liveness_proof()
        runs.append(
            {
                "label": label, "file": path.name, "run_state": res.run_state,
                "canariesRun": p["canariesRun"], "canariesPassed": p["canariesPassed"],
                "antiCanariesRun": p["antiCanariesRun"],
                "antiCanariesPassed": p["antiCanariesPassed"],
                "inapplicable": p["canariesInapplicable"],
                "indeterminate": p["canariesIndeterminate"],
                "deactivated": len(res.liveness_disposition.deactivated),
                "fraction": None if res.fraction is None else str(res.fraction.fraction),
            }
        )

    # --- the number that does not flatter us -------------------------------------------------
    whole = run_filing(TEMPLATE_COMPUTED, predicates=all_predicates())
    whole_proof = whole.liveness.as_liveness_proof()

    DOC.write_text(
        render(timing, perf_path, curve, runs, whole, whole_proof), encoding="utf-8"
    )
    print(f"PERF-CANARY2 measured: {elapsed} ms for {timing.n} executions -> {T.verdict_for(elapsed)}")
    print(f"wrote {perf_path.relative_to(REPO)} and {DOC.relative_to(REPO)}")
    return 0


def render(timing, perf_path, curve, runs, whole, whole_proof) -> str:
    rows = "\n".join(
        f"| {r['label']} | `{r['run_state']}` | {r['canariesPassed']}/{r['canariesRun']} | "
        f"{r['antiCanariesPassed']}/{r['antiCanariesRun']} | {r['inapplicable']} | "
        f"{r['indeterminate']} | {r['deactivated']} | {r['fraction'] or '`null`'} |"
        for r in runs
    )
    curve_rows = "\n".join(
        f"| {c['max_witnesses']}{' **(shipped)**' if c['max_witnesses'] == MAX_WITNESSES else ''} | "
        f"{c['canariesRun']} | {c['canariesPassed']} | {c['inapplicable']} | "
        f"{c['indeterminate']} | {'VALID' if c['valid'] else 'INVALID'} |"
        for c in curve
    )
    flat = len({(c["inapplicable"], c["indeterminate"]) for c in curve}) == 1
    return f"""# P10 — the canary cost, and the `MAX_WITNESSES` calibration curve

*Generated by `tools/measure/p10_canary_cost.py`. Re-run with `make canary-cost`.*

## `PERF-CANARY2`, MEASURED

| | |
|---|---:|
| budget | `{timing.budget_id}` |
| executions | {timing.n} (canaries + anti-canaries, over in-memory fact tables) |
| **measured** | **{timing.elapsed_ms} ms** |
| baseline (MEASURED, revised 14 Aug 2026) | {T.BASELINE_MS} ms |
| warn above / fail above | {T.WARN_ABOVE_MS} ms / {T.FAIL_ABOVE_MS} ms |
| verdict | **{T.verdict_for(timing.elapsed_ms)}** |
| written to | `{perf_path.relative_to(REPO)}` |

**This is the one number on this page that does not re-derive**, and that is what it means for a
figure to be a wall clock rather than a function of the inputs. Everything else here — the four
filings' counts, the calibration curve, the whole-harvest disposition — is byte-identical on a
fresh clone; re-running this tool moves the milliseconds and nothing else. That is precisely why
the timing lives in `reports/perf/`, outside `run.jsonl`, outside the attestation and outside
everything `verify` compares (adversary F23).

It supersedes `PERF-CANARY` (~35 ms): {T.SUPERSEDES}

**The number is read from `reports/perf/`, not from a hashed object.** `CanaryRow` carried
`elapsed_us` inside the structure whose digest feeds `livenessProof` and `run.jsonl`, which would
have made byte-identical re-derivation permanently unreachable (adversary F23). The repair moved
the timing out and kept the evidence of execution in — four deterministic fields per row, and
`canariesRun == len(rows)`.

## The four filings

| filing | run | canaries | anti-canaries | inapplicable | indeterminate | deactivated | settled fraction |
|---|---|---:|---:|---:|---:|---:|---:|
{rows}

The last column is the one to read against the third-from-last. **Inapplicability costs coverage,
it does not invalidate the run**: a predicate whose liveness could not be demonstrated on this
filing is `NOT_RUN(not_run.deactivated)`, its cells stop being settled, and the fraction falls. A
design that let the fraction stay flat while checks went undemonstrated would be the one place a
liveness layer could be gamed.

## The `MAX_WITNESSES` calibration curve (§5.1, adversary F44)

`MAX_WITNESSES = {MAX_WITNESSES}` — **{MAX_WITNESSES_STATUS}**

| `MAX_WITNESSES` | canaries run | passed | inapplicable | indeterminate | disposition |
|---:|---:|---:|---:|---:|---|
{curve_rows}

{"**The curve is FLAT, and it does not close the constant.**" if flat else "**The curve moves.**"}
{"Every setting reaches the same inapplicability on this surface, so the corpus still contains no argument for 3 over 1 — and `MAX_WITNESSES` keeps rendering `PROVISIONAL` in code, which is what §5.1's decision rule says to do when the curve does not decide. What the curve DOES establish is that raising the cap buys nothing here, so the shipped value is not costing coverage." if flat else "The setting that minimises inapplicability without raising cost is the one to ship."}

**{CALIBRATION_LABEL}**

## The number that does not flatter us

Over **all {len(whole_proof and whole.liveness.rows) if False else whole_proof['canariesRun']}
attempts across every harvested candidate**, the run is
**`{whole.run_state}` / `{whole.liveness_disposition.failure_kind}`**:
{whole_proof['canariesInapplicable']} predicates carry no stored kill case at all, so their
liveness cannot be demonstrated on any filing, and
`{whole_proof['canariesInapplicable']}/{whole_proof['canariesRun']}` is far above the
pre-registered ceiling of {CANARY_INAPPLICABLE_CEILING}.

`settledFraction` is `null` — **not zero.** Zero is a finding about the filing; null is a finding
about us.

That set is the same one the P7 funnel rejects with `g2.no_kill`. Two layers, built independently,
selecting the same predicates — which is the strongest thing either of them says about the other.
"""


if __name__ == "__main__":
    raise SystemExit(main())
