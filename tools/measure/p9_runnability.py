#!/usr/bin/env python
"""`docs/measurements/P9-relation-runnability.md` — **both integers computed, neither pinned.**

    make runnability

The number this phase produces here is `un-runnable / |catalogue|`, and the rule (F32) is that
**both** sides come from `catalogue.yaml` at render time. A literal in either position is a target
wearing a measurement's clothes; a literal in the denominator is worse, because it survives the
deletion of the rows it counts.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "src"))

from cdfc.measure.geval import gate_status, label  # noqa: E402
from cdfc.probes.relations.registry import (  # noqa: E402
    UNRUNNABLE,
    WEAKER_REVIEW,
    load,
    runnability,
)

OUT_MD = REPO / "docs" / "measurements" / "P9-relation-runnability.md"
OUT_JSON = REPO / "docs" / "measurements" / "p9-relation-runnability.json"
REVIEW = REPO / "docs" / "RELATION-REVIEW.md"


def refused_count() -> int:
    """Rows under `## Refused` in the append-only review log. Counted, not declared."""
    text = REVIEW.read_text(encoding="utf-8")
    if "## Refused" not in text:
        return 0
    body = text.split("## Refused", 1)[1]
    body = body.split("\n## ", 1)[0]
    return sum(1 for line in body.splitlines() if line.startswith("### "))


def main() -> int:
    specs = load()
    r = runnability(specs)
    refused = refused_count()
    lab = label()

    L = [
        "# P9-B2 — relation runnability, and the two counts that are the deliverable",
        "",
        "**GENERATED by `tools/measure/p9_runnability.py`. Run `make runnability`.**",
        "",
        f"**G-EVAL: {gate_status()}.**" + (f" **{lab}**" if lab else ""),
        "",
        f"**Every relation below carries `{WEAKER_REVIEW}`.** There is no second person on this "
        "project, so `plan/05` ruling (c)'s degradation applies: one signature, the literal label "
        "on every row, and the label rendered beside every relation-derived number. What is not "
        "available is a second signature nobody's calendar contains.",
        "",
        "## The number",
        "",
        f"> **{r['unrunnable']} of {r['total']} admitted relations are structurally un-runnable "
        "today.**",
        "",
        f"And beside it, the count the protocol produced: **{refused} candidates were drafted and "
        f"REFUSED** at review — `docs/RELATION-REVIEW.md` carries both with their reasons. "
        f"{refused} of {r['total'] + refused} candidates did not survive authoring.",
        "",
        "Both integers are computed at render time — the admitted count from "
        "`registry.CATALOGUE_SIZE`, the refused count from the review log's own rows. **Neither is "
        "a literal anywhere.** A layer that quietly ships `n − k` relations while claiming `n` is "
        "the coverage lie in miniature; a layer that claims a round number chosen before authoring "
        "anything is the same lie one document earlier.",
        "",
        "## By input class",
        "",
        "| class | relations | consequence for a single-filing run today |",
        "|---|---:|---|",
    ]
    consequence = {
        "FILING_ONLY": "runnable",
        "FILING_AND_BLANK": "runnable — the oracle is the pinned blank, so no corpus is needed",
        "TWO_CONSECUTIVE": f"**`NOT_RUN({UNRUNNABLE['TWO_CONSECUTIVE']})` on every run today**",
        "MANY_INSTANCES": f"**`NOT_RUN({UNRUNNABLE['MANY_INSTANCES']})` on every run today**",
        "SELF_TEST": "runs, never reported to the filer, feeds P10",
    }
    for cls in sorted(consequence):
        n = r["by_input_class"].get(cls, 0)
        L.append(f"| `{cls}` | {n} | {consequence[cls]} |")

    L += [
        "",
        "## What is un-runnable, and why — **reported, never omitted**",
        "",
        "**Absence and `NOT_RUN` are different claims, and only the second is a coverage "
        "declaration.** Each row below is authored, reviewed, loaded and reports its own reason "
        "code on every run.",
        "",
        "| id | class | subject exists at | reason reported |",
        "|---|---|---|---|",
    ]
    for row in r["unrunnable_detail"]:
        L.append(
            f"| **{row['id']}** | `{row['inputs']}` | {row['subject_exists_at']} | "
            f"`{row['reason']}` |"
        )

    L += [
        "",
        "**R-07 is un-runnable on two counts and the second is the stronger.** We hold zero real "
        "filed FME returns, so no two consecutive filings of one entity exist — that is a fact "
        "about the corpus. But the expression also needs a `prior.` root, and "
        "`cel_profile.BOUND_ROOTS` is `{filing, template}`: a third free identifier is refused at "
        "compile time, deliberately, because it is how a predicate reads something nobody "
        "declared. **The relation is not merely un-runnable; it is not expressible in the admitted "
        "subset at all**, and widening the subset for a relation that cannot be qualified against "
        "anything would open the same door for a predicate about the filing.",
        "",
        "**R-06's subject arrives at P10-B1** and the field that says so is bounded exactly as "
        "`ci/GATES.md`'s `demonstrable_red_at` is: `subject_exists_at` must name a phase in this "
        "plan, and `test_reg__no_relation_is_permanently_pending` refuses a row whose phase never "
        "comes. Its self-test returns `False` rather than `True` while the subject is absent — a "
        "self-test that passes by having nothing to check is the vacuous pass this layer exists to "
        "refuse, committed by the catcher.",
        "",
        "## Reported to the filer",
        "",
        f"**{r['reported_to_filer']} of {r['total']}.** The {r['total'] - r['reported_to_filer']} "
        "`SELF_TEST` relations measure US, not the filing. Putting one on the filer's report would "
        "put a finding about our apparatus into a document about their return, and "
        "`settledFraction` would count a cell nobody filed.",
        "",
    ]
    OUT_MD.write_text("\n".join(L), encoding="utf-8")
    OUT_JSON.write_text(
        json.dumps({"warrant": "MEASURED", "refused": refused, **r}, indent=1, sort_keys=True)
        + "\n",
        encoding="utf-8",
    )
    print(f"{r['unrunnable']} of {r['total']} un-runnable · {refused} refused at review")
    print(f"wrote {OUT_MD.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
