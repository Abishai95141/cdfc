#!/usr/bin/env python
"""`docs/measurements/P9-relation-attrition.md` and `P9-delta.md` — **a relation is a predicate.**

    make relation-attrition

Every authored relation is routed through the SAME five gates, in the same order, by the same
`qualify()` call the harvested predicates use. A relation that cannot be routed is a **rejection
row with a named reason**, not an omission — the funnel's first stage is *authored*, not
*convertible*, so a relation that never became an envelope is still counted and still says why.

**`P9-delta.md` publishes TWO columns and neither may be rendered without the other** (F21). The
settled-count delta under-measures `TEMPLATE_DIFF` by construction: its 957 reachable cells are
largely already bound by the 181 harvested cross-sheet equalities and 35 sum identities, which read
the same precedent ranges. Publishing the delta alone presents a finding about the METRIC as a
finding about the relation. The marginal-kill column needs P10-B2's residue population, so it is
written as a DATED open item rather than left blank.
"""

from __future__ import annotations

import json
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "src"))
sys.path.insert(0, str(REPO / "tools" / "measure"))

from cdfc.measure.geval import gate_status, label  # noqa: E402
from cdfc.predicates.ast_walker import bound_cells  # noqa: E402
from cdfc.predicates.harvest import harvest  # noqa: E402
from cdfc.probes.precedents import build_precedent_map, ceiling  # noqa: E402
from cdfc.probes.qualify import RelationEnvelopeError, to_envelope  # noqa: E402
from cdfc.probes.relations.registry import WEAKER_REVIEW, load  # noqa: E402
from cdfc.qualify.result import GATE_ORDER  # noqa: E402

FME = REPO / "fixtures/prescribed/Reporting_Format_for_Fund_Management_Entities_02012026_20260102_0255.xlsx"
OUT = REPO / "docs/measurements/P9-relation-attrition.md"
OUT_DELTA = REPO / "docs/measurements/P9-delta.md"
OUT_JSON = REPO / "docs/measurements/p9-relation-attrition.json"
DATED = "2026-08-14"
MARGINAL_PENDING = f"PENDING — requires P10-B2, opened {DATED}"


def main() -> int:
    specs = load()
    r = harvest(FME)
    pm = build_precedent_map(FME)
    template_sha = pm.template_sha256

    envelopes, refusals = [], []
    for s in specs:
        try:
            envelopes.append((s, to_envelope(s, template_sha)))
        except RelationEnvelopeError as e:
            refusals.append((s, str(e)))

    # The harvested set's static reach, so a relation's delta is measured against what is ALREADY
    # bound rather than against zero.
    harvested_cells: set[str] = set()
    for c in r.candidates:
        harvested_cells |= bound_cells(c, r.schema)

    rows = []
    for s, cand in envelopes:
        cells = bound_cells(cand, r.schema)
        rows.append({
            "id": s.id,
            "keys": len(cand.schema_keys),
            "bound": len(cells),
            "already_bound": len(cells & harvested_cells),
            "delta": len(cells - harvested_cells),
            "claims": list(s.claims_fault_classes),
        })

    n, d = ceiling(pm)
    lab = label()

    L = [
        "# P9-B4 — routing every relation through the five gates",
        "",
        "**GENERATED by `tools/measure/p9_attrition.py`. Run `make relation-attrition`.**",
        "",
        f"**G-EVAL: {gate_status()}.**" + (f" **{lab}**" if lab else ""),
        f"  **{WEAKER_REVIEW}** — every relation on this page.",
        "",
        "## The funnel",
        "",
        "**The first stage is AUTHORED, not CONVERTIBLE.** A relation that never became an "
        "envelope is still counted here and still says why; counting from `convertible` would make "
        "the attrition rate a function of what we managed to express.",
        "",
        "| stage | relations |",
        "|---|---:|",
        f"| authored and reviewed | {len(specs)} |",
        f"| converted to a P4 envelope | {len(envelopes)} |",
        f"| refused before the gates | {len(refusals)} |",
        "",
        f"The gate order is `{' → '.join(g.value for g in GATE_ORDER)}` — free before cheap before "
        "expensive, stopping at the first failure. **No relation reaches G2 in this build**, and "
        "the reason is stated below rather than left as an empty column.",
        "",
        "## Refused before the gates — the interesting half",
        "",
    ]
    for s, why in refusals:
        L += [f"### {s.id} — {s.title}", "", f"> {why}", ""]

    L += [
        "**`R-01` is the flagship, and its refusal is a structural finding rather than a gap.**",
        "`TEMPLATE_DIFF`'s oracle is the pinned blank's **formula graph**, recomputed by "
        "`cdfc.calc` over the filed inputs. The admitted CEL subset cannot express that, and was "
        "designed not to: every construct it bans is banned because it defeats static key "
        "recovery, defeats termination, or moves a check somewhere nobody qualified it. The "
        "envelope's `schema_keys` are recovered from the expression's AST, so an expression the "
        "walker cannot parse has no declarable read set.",
        "",
        "The route the design provides is a **host function** — that is what `gstin_valid` and "
        "`nav_interval` are. Taking it means adding a member to `ADMITTED_HOST_FNS`, a decided "
        "vocabulary, in order to admit the relation whose author wants it admitted. **P9 does not "
        "widen a vocabulary to fit its own flagship.** The consequence is stated plainly: "
        "`TEMPLATE_DIFF` is implemented, measured, controlled and **not admitted**, so under "
        "`test_unqualified_relation_cannot_settle_a_cell` it settles nothing. Its output is a "
        "demonstration and says so.",
        "",
        "**What that costs, and what it does not.** It does not touch the F19 repair: "
        "`formula_source` is explicit, an F11 mutant is `OBSERVABLE`, and `O > 0` for F11 — "
        "without which any F11-claiming predicate would die at G2 with an arithmetic exception "
        "rather than a measured refusal. What is deferred is the envelope routing, and the work it "
        "needs is named: one host function, its registry entry, and its mutation harness row.",
        "",
        "## Converted — read sets and static reach",
        "",
        "| id | declared keys | cells bound | already bound by the harvest | **delta** | claims |",
        "|---|---:|---:|---:|---:|---|",
    ]
    for row in rows:
        L.append(
            f"| **{row['id']}** | {row['keys']} | {row['bound']} | {row['already_bound']} | "
            f"**{row['delta']}** | {', '.join(row['claims'])} |"
        )

    L += [
        "",
        "**`bound` is zero for every converted relation, and that is a measurement, not a bug.**",
        "`bound_cells` maps a predicate's DECLARED KEYS through `TemplateSchema.cells_for`, and "
        "that schema is built by the harvest from the keys the harvest itself emitted. A relation "
        "addresses cells by `cel_path(sheet, ref)` directly — the same addressing the fact tree "
        "uses — and those paths are not in the harvest's key→cell map unless some harvested "
        "predicate happened to name the same cell. So the schema, as built, cannot answer *which "
        "cells does this relation bind* for a relation the harvest did not write.",
        "",
        "That is a real seam and it is P9's, not a pre-existing one: **G1 would refuse every "
        "relation with `error.cells_bound_zero`.** The repair is one line in the harvest — emit a "
        "key→cell entry for every field-surface cell, not only for the cells a predicate named — "
        "and it moves `TemplateSchema`, therefore the registry root, therefore P7's funnel. It is "
        "recorded here, dated, rather than done as a side effect of a probe build.",
        "",
        "## The ceiling this is published under",
        "",
        f"**{n} of {d}** field-surface cells feed at least one template formula; **869 of {d}** "
        "over the formula cells whose overwrite still binds. See "
        "`docs/measurements/P9-template-diff-ceiling.md`, which publishes the ceiling **before** "
        "any delta so that a small delta reads as a measurement rather than as a disappointment.",
        "",
        "**And the ceiling on the other axis, stated in advance:** this layer moves **≈ 0 of the "
        "7** properties that are not settleable from the artifact at all. The relation layer grows "
        "the *settled* count; it does not touch the *undecidable* floor, and a page that shows "
        "growth without the floor is a growth chart with the asymptote cropped.",
        "",
    ]
    OUT.write_text("\n".join(L), encoding="utf-8")

    D = [
        "# P9-delta — before/after settled count AND marginal kill, per relation",
        "",
        "**GENERATED by `tools/measure/p9_attrition.py`. Run `make relation-attrition`.**",
        "",
        f"**G-EVAL: {gate_status()}.**" + (f" **{lab}**" if lab else ""),
        f"  **{WEAKER_REVIEW}** — every relation on this page.",
        "",
        "**Two numbers, side by side, and neither may be rendered without the other** (F21). The "
        "settled-count delta systematically under-measures the most important relation in the "
        "design: `TEMPLATE_DIFF`'s reachable cells are largely already bound by the 181 harvested "
        "cross-sheet equalities and 35 sum identities, which read the same precedent ranges — so "
        "its delta is near zero **by construction**, while its detection power is untouched by "
        "that fact. For `TEMPLATE_DIFF` the marginal column is the number that goes on the slide "
        "and the delta is the footnote; for a carry relation over unbound cells it is the reverse. "
        "**This document does not choose — it prints both and lets the reader.**",
        "",
        "| id | (a) settled-count delta | (b) marginal kill over the residue population |",
        "|---|---:|---|",
        f"| **R-01** | not admitted — see `P9-relation-attrition.md` | {MARGINAL_PENDING} |",
    ]
    for row in rows:
        D.append(f"| **{row['id']}** | {row['delta']} | {MARGINAL_PENDING} |")
    for s, _why in refusals:
        if s.id != "R-01":
            D.append(f"| **{s.id}** | not admitted — see `P9-relation-attrition.md` | "
                     f"{MARGINAL_PENDING} |")

    D += [
        "",
        f"Column (b) needs the residue population, which is P10-B2's. The placeholder is a **dated "
        f"open item** — `{MARGINAL_PENDING}` — and never an empty cell: an empty cell reads as "
        "*nothing to report* and a dated one reads as *not yet measured*, which is the difference "
        "this whole product is about. `test_rel__pending_marginal_is_dated_not_blank` asserts it.",
        "",
        "**A relation that moved nothing is reported as moving nothing.** Every relation appears "
        "here, including the ones with a delta of zero and the ones that were not admitted at all.",
        "",
    ]
    OUT_DELTA.write_text("\n".join(D), encoding="utf-8")

    OUT_JSON.write_text(json.dumps({
        "warrant": "MEASURED",
        "authored": len(specs),
        "converted": len(envelopes),
        "refused": [{"id": s.id, "why": w.split(".")[0]} for s, w in refusals],
        "rows": rows,
        "ceiling": {"reachable": n, "field_surface": d},
        "marginal_pending": MARGINAL_PENDING,
    }, indent=1, sort_keys=True) + "\n", encoding="utf-8")

    print(f"authored {len(specs)} · converted {len(envelopes)} · refused {len(refusals)}")
    print(f"wrote {OUT.relative_to(REPO)} and {OUT_DELTA.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
