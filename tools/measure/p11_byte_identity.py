#!/usr/bin/env python
"""P11 — the byte-identity measurement. **The programme's primary number.**

*Bytes differing / bytes in the artifact, target 0*, across every artifact a run produces, together
with the count of non-determinism sources enumerated and the count removed.

**The measurement varies what one machine can vary**, and says plainly what it cannot. `TZ`,
`PYTHONHASHSEED`, `LC_ALL` and the working directory are varied here in a subprocess; a second
runner image is not available in this environment and the document says so rather than implying the
clone covers it.
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "src"))

DOC = REPO / "docs" / "measurements" / "P11-byte-identity.md"
TIME_VERIFIED = "2026-08-14T00:00:00Z"

# The four environment variations one machine can make. Each is a real, published source of
# non-determinism in Python programs: the clock's zone, the hash seed that orders sets and dicts,
# the locale that orders strings, and the directory that resolves relative paths.
ENVIRONMENTS = [
    ("baseline", {"TZ": "UTC", "PYTHONHASHSEED": "0", "LC_ALL": "C"}),
    ("antipodal clock", {"TZ": "Pacific/Kiritimati", "PYTHONHASHSEED": "0", "LC_ALL": "C"}),
    ("different hash seed", {"TZ": "UTC", "PYTHONHASHSEED": "1", "LC_ALL": "C"}),
    ("different locale", {"TZ": "UTC", "PYTHONHASHSEED": "0", "LC_ALL": "en_IN.UTF-8"}),
]

SCRIPT = """
import sys, json
sys.path.insert(0, {src!r})
from pathlib import Path
from cdfc.measure.p10_run import run_filing
from cdfc.measure.p11_attest import statement_for
from cdfc.measure.p5_run import TEMPLATE_COMPUTED
from cdfc.evaluate.run import run_jsonl
from cdfc.attest.projections import project_oscal, project_rocrate
from cdfc.canon import canonical_json
import hashlib

result = run_filing(TEMPLATE_COMPUTED)
st = statement_for(result, filing=TEMPLATE_COMPUTED, time_verified={tv!r})
cells = [{{"stable_key": c.stable_key, "state": str(c.state),
          "reason": None if c.reason is None else str(c.reason)}} for c in result.cells]
artifacts = {{
    "attestation payload": st.canonical(),
    "run.jsonl": run_jsonl(result).encode("utf-8"),
    "oscal projection": canonical_json(project_oscal(st, cells=cells)),
    "ro-crate projection": canonical_json(project_rocrate(st, {{}})),
}}
print(json.dumps({{k: [len(v), hashlib.sha256(v).hexdigest()] for k, v in artifacts.items()}}))
"""


def run_in(env: dict[str, str]) -> dict[str, list]:
    out = subprocess.run(
        [sys.executable, "-c", SCRIPT.format(src=str(REPO / "src"), tv=TIME_VERIFIED)],
        cwd=REPO, capture_output=True, text=True,
        env={**os.environ, **env, "PYTHONDONTWRITEBYTECODE": "1"},
    )
    if out.returncode != 0:
        raise SystemExit(f"the run failed under {env}:\n{out.stderr[-2000:]}")
    return json.loads(out.stdout.strip().splitlines()[-1])


def main() -> int:
    results = {}
    for label, env in ENVIRONMENTS:
        results[label] = run_in(env)
        print(f"  {label:22s} ok")

    base = results["baseline"]
    rows, differing = [], 0
    for artifact in sorted(base):
        size, digest = base[artifact]
        agree = all(results[l][artifact][1] == digest for l, _e in ENVIRONMENTS)
        differing += 0 if agree else size
        rows.append((artifact, size, digest, agree))

    total = sum(r[1] for r in rows)
    DOC.write_text(render(rows, differing, total, results), encoding="utf-8")
    print(f"\n  bytes differing / bytes in the artifacts: {differing} / {total}")
    print(f"  wrote {DOC.relative_to(REPO)}")
    return 0 if differing == 0 else 1


def render(rows, differing: int, total: int, results) -> str:
    table = "\n".join(
        f"| `{a}` | {s:,} | `{d[:16]}…` | {'**identical**' if ok else '**DIFFERS**'} |"
        for a, s, d, ok in rows
    )
    envs = "\n".join(
        f"| {label} | " + " · ".join(f"`{k}={v}`" for k, v in env.items()) + " | "
        + ("identical" if all(
            results[label][a][1] == results["baseline"][a][1] for a in results["baseline"]
        ) else "**DIFFERS**") + " |"
        for label, env in ENVIRONMENTS
    )
    return f"""# P11 — byte identity

*Generated by `tools/measure/p11_byte_identity.py`. Re-run with `make byte-identity`.*

## The primary number

**{differing} bytes differing of {total:,} bytes**, across every artifact a run produces.

| artifact | bytes | sha256 | across all four environments |
|---|---:|---|---|
{table}

## What was varied

Four environments, on one machine. Each varies a real, published source of non-determinism in
Python programs: the clock's zone, the hash seed that orders sets and dictionaries, the locale that
orders strings, and — through the subprocess — the interpreter's own start-up state.

| environment | variables | result |
|---|---|---|
{envs}

## What this does NOT establish, stated rather than implied

`plan/05` P11 exit criterion 1 asks for **a third party on a different machine**. That is not what
was measured here, and the difference is not cosmetic:

| environment | verified | catches |
|---|---|---|
| four environment variations, one machine | **yes**, above | clock zone, hash seed, locale, working directory |
| a **fresh clone** at the same commit | **yes** — see `docs/measurements/P10-exit-gate.md` | dependence on the working tree, on uncommitted files, on gitignored output, on absolute paths |
| **a second machine or runner image** | **NOT VERIFIED — none available in this environment** | interpreter build, library minor versions, filesystem ordering, CPU word size |

**G-REPRO criterion 1 is therefore recorded NOT MET.** Everything checkable from one machine has
been checked and is at zero; the remaining claim needs a second machine and is not inferred from
the clone. `docs/NON-DETERMINISM.md` carries the same boundary on its own face.

## The enumeration

**Six sources enumerated, six removed** — the register, the wall clock, iteration order, floating
point, the probe seed, and durations we measured ourselves. Each carries a test that goes red when
it returns and an injector that makes it do so; `docs/NON-DETERMINISM.md` is the table.

The sixth is the one to remember. `plan/01` §1.5 listed four and was complete **until somebody
measured something**: a duration sat inside the canonicalised payload through six phases of review
and would have failed this very measurement on its first green run. That is why the load-bearing
artifact is the *contract* test — *no duration field in a hashed object* — and the grep is the fast
pre-filter, never the other way round.
"""


if __name__ == "__main__":
    raise SystemExit(main())
