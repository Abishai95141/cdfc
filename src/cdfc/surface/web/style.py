"""The app stylesheet. **Generated from `design.py`, like the report's — never hand-written.**

`stylesheet.py` emits the report's CSS from the tokens so a colour outside the palette cannot
appear on the attested artifact. This does the same for the twelve screens, and it extends rather
than forks: `app_stylesheet()` begins with `stylesheet()` verbatim, so a screen and the report
render a hero, a band and a table identically. Two stylesheets that drift are two products.

## What the app layer adds, and why each is a decision rather than a flourish

* **A shell** — a rail of screens on the left at desktop width, a horizontal strip on a phone. The
  nav is a `<nav>` of ordinary links; every screen is reachable with scripting off.
* **Spacing on the 8px base**, with white space used to SEPARATE MEANINGS rather than to decorate:
  the gap between a count and its admission caveat is `xs` because they are one statement, and the
  gap between two sections is `section` because they are not.
* **Tabular figures everywhere a number appears.** `figure-md` is the mono face at body size, and
  a column of counts that does not align is a column a reader skims instead of reads.
* **A focus ring that is never removed.** `:focus-visible` gets a 2px `accent-ink` outline with an
  offset; there is no `outline: none` in this file. A keyboard user losing the caret on a coverage
  screen is a keyboard user who cannot audit it.

## What it does not have

No green. The palette has none — `design.py` defines no affirmative colour — and
`test_style__no_colour_falls_in_the_green_hue_band` reads the GENERATED BYTES rather than the token
table, because the fastest way to reintroduce an affirmative colour is to add it under a name
nobody would grep for.
"""

