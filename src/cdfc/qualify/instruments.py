"""P7-B0 — the instrument corpus: what is addressable, and what is declared absent.

`corpus/instruments/` holds one `<instrument_id>.text.json` per pinned artifact plus a
`MANIFEST.json` that is the corpus's own census. Both are GENERATED by `tools/build_instruments.py`
and both are content-addressed.

**D-P7-01 — THE STATUTORY CORPUS IS EMPTY, AND THAT IS PUBLISHED RATHER THAN ASSUMED.**
`plan/04-phases-qualification.md` E7.6 asserts *"the regulation PDF and the 399-circular corpus are
on disk and content-addressed"* as a precondition of this phase. **They are not on disk.** No
instrument of `kind: STATUTE` exists in this repository, so:

  * no obligation may carry `source: STATUTE` — `obligations.load` refuses one whose instrument is
    absent from this manifest, rather than letting it resolve against nothing;
  * P7's obligation-coverage pair reads `predicates_with_a_STATUTE_obligation = 0 / N` for a
    HARDER reason than the plan expected: not *"no harvested predicate cites a statute yet"* but
    *"no statute is pinned in this repository at all"*;
  * `MANIFEST.json` carries `statute_instruments: []` with that reason as a string, so the absence
    is a field with a value rather than a section nobody wrote.

*The alternative it beat:* synthesising a plausible instrument text so the pipeline had something
to point at. Rejected outright — a fabricated instrument would make every G0 figure computed
against it meaningless, and the number this phase exists to produce is an attrition funnel whose
first stage is *"does this predicate's construct exist in the artifact it claims"*. The remedy is a
pinned PDF and a second extractor, and the drop-in point is `textsource.build()`, which takes
`Extraction` objects and does not know what produced them.
"""

from __future__ import annotations

import json
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Final

from cdfc.canon import canonical_json, digest
from cdfc.qualify.textsource import (
    Corroboration,
    DisputedRegion,
    ExtractionManifest,
    InstrumentText,
    ResolvedUnit,
    TextSourceError,
)

CORPUS: Final[Path] = Path("corpus/instruments")

STATUTE_ABSENT_REASON: Final[str] = (
    "No statutory instrument is pinned in this repository. P7's entry criterion E7.6 asserted a "
    "regulation PDF and a 399-circular corpus as already on disk; neither is. Until one is pinned "
    "AND read by two independent extractors, every obligation in this system is a TEMPLATE "
    "obligation and the published pair reads predicates_with_a_STATUTE_obligation = 0/N. "
    "Fabricating a text so the pipeline had something to point at was rejected: a span into an "
    "invented instrument is not evidence, and it would make every G0 number meaningless while "
    "looking like progress."
)


class InstrumentNotFound(LookupError):
    """The instrument an obligation names is not in the corpus. Never resolved against nothing."""


@dataclass(frozen=True, slots=True)
class InstrumentRow:
    instrument_id: str
    kind: str  # TEMPLATE | STATUTE
    source_name: str
    source_sha256: str
    text_sha256: str
    units_total: int
    agreed: int
    single_party: int
    disputed: int
    external: tuple[int, int]
    same_author: tuple[int, int]


def serialise(it: InstrumentText, *, kind: str, source_name: str, source_sha256: str) -> bytes:
    """RFC 8785 bytes. The file IS the canonical form, so a re-read cannot drift from the digest."""
    payload = {
        "instrument_id": it.instrument_id,
        "kind": kind,
        "source_name": source_name,
        "source_sha256": source_sha256,
        "sha256": it.sha256,
        "text": it.text,
        "transformations": [list(t) for t in it.transformations],
        "refused_transformations": [list(t) for t in it.refused_transformations],
        "units": [
            {
                "key": u.key,
                "page": u.page,
                "span": list(u.span),
                "corroboration": u.corroboration.value,
                "parties": list(u.parties),
                "external_party": u.external_party,
            }
            for u in it.units
        ],
        "disputed": [
            {"key": d.key, "page": d.page, "span": list(d.span),
             "readings": dict(sorted(d.readings.items()))}
            for d in it.disputed
        ],
        "manifests": [
            {
                "extractor": m.extractor, "version": m.version, "external": m.external,
                "sha256": m.sha256, "n_units": m.n_units, "n_disputed": m.n_disputed,
                "n_blind": m.n_blind, "exclusion_mechanisms": list(m.exclusion_mechanisms),
            }
            for m in it.manifests
        ],
    }
    return canonical_json(payload)


def deserialise(blob: bytes) -> tuple[InstrumentText, str, str, str]:
    """`(instrument, kind, source_name, source_sha256)`, with the digest RE-DERIVED, not trusted.

    A stored text whose recorded `sha256` does not match what the stored fields hash to is a
    corrupted or hand-edited artifact, and it raises. This is the one place a span could silently
    start pointing at different characters.
    """
    obj: Mapping[str, Any] = json.loads(blob.decode("utf-8"))
    it = InstrumentText(
        instrument_id=obj["instrument_id"],
        text=obj["text"],
        units=tuple(
            ResolvedUnit(
                key=u["key"], page=u["page"], span=(u["span"][0], u["span"][1]),
                corroboration=Corroboration(u["corroboration"]),
                parties=tuple(u["parties"]), external_party=u["external_party"],
            )
            for u in obj["units"]
        ),
        disputed=tuple(
            DisputedRegion(key=d["key"], page=d["page"], span=(d["span"][0], d["span"][1]),
                           readings=dict(d["readings"]))
            for d in obj["disputed"]
        ),
        manifests=tuple(
            ExtractionManifest(
                extractor=m["extractor"], version=m["version"], external=m["external"],
                sha256=m["sha256"], n_units=m["n_units"], n_disputed=m["n_disputed"],
                n_blind=m["n_blind"], exclusion_mechanisms=tuple(m["exclusion_mechanisms"]),
            )
            for m in obj["manifests"]
        ),
        transformations=tuple((a, b) for a, b in obj["transformations"]),
        refused_transformations=tuple((a, b) for a, b in obj["refused_transformations"]),
        sha256=obj["sha256"],
    )
    recomputed = digest({
        "instrument_id": it.instrument_id,
        "transformations": [list(t) for t in it.transformations],
        "refused_transformations": [list(t) for t in it.refused_transformations],
        "units": [
            [u.key, u.page, u.corroboration.value, list(u.parties), u.external_party, *u.span]
            for u in it.units
        ],
        "text": it.text,
        "manifests": [
            [m.extractor, m.version, m.external, m.sha256, m.n_units, m.n_disputed, m.n_blind,
             list(m.exclusion_mechanisms)]
            for m in it.manifests
        ],
    })
    if recomputed != it.sha256:
        raise TextSourceError(
            f"{it.instrument_id}: the stored digest is {it.sha256[:16]}… but the stored fields "
            f"hash to {recomputed[:16]}…. Either the file was hand-edited or it was written by a "
            "different build. Every span recorded against this instrument points somewhere else."
        )
    return it, obj["kind"], obj["source_name"], obj["source_sha256"]


def row_of(it: InstrumentText, *, kind: str, source_name: str, source_sha256: str) -> InstrumentRow:
    c = it.counts()
    ag = it.agreement()
    return InstrumentRow(
        instrument_id=it.instrument_id,
        kind=kind,
        source_name=source_name,
        source_sha256=source_sha256,
        text_sha256=it.sha256,
        units_total=c["units_total"],
        agreed=c[Corroboration.AGREED.value],
        single_party=c[Corroboration.SINGLE_PARTY.value],
        disputed=c[Corroboration.DISPUTED.value],
        external=ag["EXTERNAL"],
        same_author=ag["SAME_AUTHOR"],
    )


def manifest_bytes(rows: Sequence[InstrumentRow]) -> bytes:
    statute = [r for r in rows if r.kind == "STATUTE"]
    return canonical_json({
        "instruments": [
            {
                "instrument_id": r.instrument_id, "kind": r.kind, "source_name": r.source_name,
                "source_sha256": r.source_sha256, "text_sha256": r.text_sha256,
                "units_total": r.units_total, "agreed": r.agreed,
                "single_party": r.single_party, "disputed": r.disputed,
                "agreement_external": list(r.external),
                "agreement_same_author": list(r.same_author),
            }
            for r in sorted(rows, key=lambda r: r.instrument_id)
        ],
        "statute_instruments": [r.instrument_id for r in statute],
        "statute_absent_reason": "" if statute else STATUTE_ABSENT_REASON,
    })


class InstrumentStore:
    """Read-only access to the pinned corpus. The only way a gate reaches an instrument text."""

    def __init__(self, root: Path = CORPUS) -> None:
        self._root = root
        self._cache: dict[str, InstrumentText] = {}
        self._kinds: dict[str, str] = {}

    @property
    def root(self) -> Path:
        return self._root

    def ids(self) -> tuple[str, ...]:
        return tuple(sorted(p.name[: -len(".text.json")] for p in self._root.glob("*.text.json")))

    def get(self, instrument_id: str) -> InstrumentText:
        if instrument_id not in self._cache:
            path = self._root / f"{instrument_id}.text.json"
            if not path.is_file():
                raise InstrumentNotFound(
                    f"{instrument_id!r} is not in {self._root}. Known: {list(self.ids())}. An "
                    "obligation whose instrument is absent does not resolve against an empty "
                    "string — it does not resolve at all."
                )
            it, kind, _name, _sha = deserialise(path.read_bytes())
            self._cache[instrument_id] = it
            self._kinds[instrument_id] = kind
        return self._cache[instrument_id]

    def kind_of(self, instrument_id: str) -> str:
        self.get(instrument_id)
        return self._kinds[instrument_id]

    def statute_ids(self) -> tuple[str, ...]:
        return tuple(i for i in self.ids() if self.kind_of(i) == "STATUTE")

    def in_memory(self, it: InstrumentText, *, kind: str = "TEMPLATE") -> None:
        """Register an instrument built this run. Tests and `cdfc qualify` both use it so a gate
        never has to be handed a bare text with no identity."""
        self._cache[it.instrument_id] = it
        self._kinds[it.instrument_id] = kind
